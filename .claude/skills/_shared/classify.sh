#!/usr/bin/env bash
#
# classify.sh — 키워드 → 카테고리 결정론 분류기 (사전 기반, 모델 0)
#
# 왜 이 스크립트가 있나:
#   텔레그램 /capture 노티스를 2초 안에 보내려면 분류를 claude -p(콜드 스타트 ~10s)나
#   서브에이전트 없이 해야 한다. 카테고리 6종은 규칙이 단순해서 키워드 사전만으로 충분히
#   맞는다. 애매하면 '기타'로 떨어뜨린다.
#
#   사전은 _shared/classifier-agent.md 의 카테고리별 예시 키워드에서 파생한다.
#   규칙을 바꿀 때는 그 파일과 아래 목록을 함께 갱신한다(단일 규칙, 두 표현).
#
#   매칭 규칙 = "가장 긴 매칭 키워드가 이긴다":
#     - 입력에 여러 키워드가 걸리면 더 긴(=더 구체적인) 키워드의 카테고리를 택한다.
#       예: "약속"은 '약'(건강)과 '약속'(일상)에 모두 걸리지만 더 긴 '약속' → 일상.
#     - 길이가 같으면 아래 목록에서 먼저 나온 카테고리가 이긴다(우선순위).
#       예: "헬스장 등록비 납부"는 '헬스'(건강)·'납부'(금융) 둘 다 길이 2 → 건강이 먼저라 건강.
#
#   호환성: macOS 기본/텔레그램 리스너의 bash 3.2 에서 동작해야 하므로 nameref·연관배열을
#   쓰지 않는다(순수 while-read + case 글롭).
#
# 사용법:
#   classify.sh "<키워드/문장>"      # 카테고리 한 단어를 stdout 으로 출력
#
set -euo pipefail

input="${1:-}"

# "키워드 카테고리" 목록. 우선순위(길이 동률 시 tie-break)는 등장 순서 = 건강>스터디>금융>업무>일상.
entries='
병원 건강
운동 건강
검진 건강
헬스 건강
산책 건강
수면 건강
복약 건강
약국 건강
진료 건강
처방 건강
강의 스터디
자격증 스터디
세미나 스터디
공부 스터디
학습 스터디
과제 스터디
읽기 스터디
납부 금융
이체 금융
세금 금융
보험 금융
카드 금융
환전 금융
저축 금융
미팅 업무
리포트 업무
데드라인 업무
리뷰 업무
회의 업무
발표 업무
제안서 업무
장보기 일상
청소 일상
약속 일상
취미 일상
쇼핑 일상
요리 일상
빨래 일상
'

best_len=0
best_cat="기타"
while read -r kw cat; do
  [ -z "$kw" ] && continue
  case "$input" in
    *"$kw"*)
      klen=${#kw}
      if [ "$klen" -gt "$best_len" ]; then
        best_len="$klen"
        best_cat="$cat"
      fi
      ;;
  esac
done <<EOF
$entries
EOF

printf '%s' "$best_cat"
